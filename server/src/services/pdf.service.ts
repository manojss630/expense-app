import PDFDocument from 'pdfkit';
import { v4 as uuidv4 } from 'uuid';
import { formatCurrency, formatDate, ExpenseWithDetails, ReportSummary } from '@expense-app/shared';

interface GeneratedReport {
  id: string;
  buffer: Buffer;
  filename: string;
  createdAt: Date;
}

const reportsCache = new Map<string, GeneratedReport>();

export class PdfService {
  static getCachedReport(id: string): GeneratedReport | undefined {
    return reportsCache.get(id);
  }

  static async generateExpenseReport(
    summary: ReportSummary,
    expenses: ExpenseWithDetails[],
    options: {
      title?: string;
      preparedFor?: string;
      generatedBy?: string;
    }
  ): Promise<{ reportId: string; buffer: Buffer; filename: string }> {
    return new Promise((resolve, reject) => {
      try {
        const doc = new PDFDocument({
          size: 'A4',
          margin: 40,
          info: {
            Title: options.title || 'Expense Statement Report',
            Author: 'ExpenseApp',
          },
        });

        const buffers: Buffer[] = [];
        doc.on('data', buffers.push.bind(buffers));
        doc.on('end', () => {
          const pdfBuffer = Buffer.concat(buffers);
          const reportId = uuidv4();
          const safeName = (options.preparedFor || 'All-Members').replace(/[^a-zA-Z0-9_-]/g, '_');
          const filename = `Expense_Report_${safeName}_${new Date().toISOString().split('T')[0]}.pdf`;

          reportsCache.set(reportId, {
            id: reportId,
            buffer: pdfBuffer,
            filename,
            createdAt: new Date(),
          });

          resolve({ reportId, buffer: pdfBuffer, filename });
        });

        // --------------------------------------------------------------------
        // PDF Design & Rendering
        // --------------------------------------------------------------------
        const primaryColor = '#4F46E5'; // Indigo
        const secondaryColor = '#0F172A'; // Slate 900
        const textMuted = '#64748B'; // Slate 500
        const borderLight = '#E2E8F0'; // Slate 200

        // Header Banner / Logo
        doc
          .rect(40, 40, 515, 60)
          .fill(primaryColor);

        doc
          .fontSize(22)
          .fillColor('#FFFFFF')
          .text('EXPENSE APP', 60, 52, { characterSpacing: 1.5 });

        doc
          .fontSize(10)
          .fillColor('#E0E7FF')
          .text('Official Expense Statement & Financial Summary', 60, 78);

        // Report Metadata Section
        doc.moveDown(3);
        const startY = 120;

        doc
          .fontSize(14)
          .fillColor(secondaryColor)
          .text(options.title || 'Expense Statement', 40, startY);

        doc
          .fontSize(9)
          .fillColor(textMuted)
          .text(`Date Range: ${summary.fromDate || 'All Time'} to ${summary.toDate || 'Present'}`, 40, startY + 20)
          .text(`Person: ${options.preparedFor || summary.memberName || 'All Family Members'}`, 40, startY + 34)
          .text(`Generated by: ${options.generatedBy || 'ExpenseApp User'}`, 350, startY + 20)
          .text(`Generated on: ${new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' })}`, 350, startY + 34);

        // Summary Metric Boxes
        const boxY = startY + 60;
        const boxWidth = 160;
        const boxHeight = 52;

        // Box 1: Selected Total
        doc
          .roundedRect(40, boxY, boxWidth, boxHeight, 6)
          .fillAndStroke('#EEF2FF', '#C7D2FE');
        doc
          .fontSize(9)
          .fillColor(primaryColor)
          .text('STATEMENT TOTAL', 55, boxY + 10);
        doc
          .fontSize(16)
          .fillColor(secondaryColor)
          .text(formatCurrency(summary.customRangeTotal), 55, boxY + 26);

        // Box 2: Total Transactions
        doc
          .roundedRect(215, boxY, boxWidth, boxHeight, 6)
          .fillAndStroke('#F8FAFC', borderLight);
        doc
          .fontSize(9)
          .fillColor(textMuted)
          .text('TRANSACTIONS COUNT', 230, boxY + 10);
        doc
          .fontSize(16)
          .fillColor(secondaryColor)
          .text(`${summary.totalCount} entries`, 230, boxY + 26);

        // Box 3: Month-to-date
        doc
          .roundedRect(390, boxY, boxWidth, boxHeight, 6)
          .fillAndStroke('#F8FAFC', borderLight);
        doc
          .fontSize(9)
          .fillColor(textMuted)
          .text('THIS MONTH OVERALL', 405, boxY + 10);
        doc
          .fontSize(16)
          .fillColor(secondaryColor)
          .text(formatCurrency(summary.thisMonthTotal), 405, boxY + 26);

        // Category Breakdown Mini-table
        let currentY = boxY + 75;
        if (summary.categoryTotals.length > 0) {
          doc
            .fontSize(11)
            .fillColor(secondaryColor)
            .text('Category Breakdown', 40, currentY);

          currentY += 18;
          doc
            .rect(40, currentY, 515, 20)
            .fill('#F1F5F9');

          doc
            .fontSize(9)
            .fillColor(secondaryColor)
            .text('Category', 50, currentY + 5)
            .text('Share', 240, currentY + 5)
            .text('Count', 360, currentY + 5)
            .text('Amount', 460, currentY + 5, { width: 85, align: 'right' });

          currentY += 20;

          summary.categoryTotals.slice(0, 5).forEach((cat) => {
            doc
              .fontSize(9)
              .fillColor(secondaryColor)
              .text(cat.categoryName, 50, currentY + 4)
              .text(`${cat.percentage}%`, 240, currentY + 4)
              .text(`${cat.count}`, 360, currentY + 4)
              .text(formatCurrency(cat.total), 460, currentY + 4, { width: 85, align: 'right' });

            doc
              .moveTo(40, currentY + 18)
              .lineTo(555, currentY + 18)
              .strokeColor(borderLight)
              .stroke();

            currentY += 19;
          });
        }

        // Detailed Transactions Table
        currentY += 20;
        doc
          .fontSize(11)
          .fillColor(secondaryColor)
          .text('Itemized Transaction Details', 40, currentY);

        currentY += 18;
        doc
          .rect(40, currentY, 515, 22)
          .fill(secondaryColor);

        doc
          .fontSize(9)
          .fillColor('#FFFFFF')
          .text('Date', 50, currentY + 6)
          .text('Person', 120, currentY + 6)
          .text('Category', 210, currentY + 6)
          .text('Note / Description', 300, currentY + 6)
          .text('Amount', 460, currentY + 6, { width: 85, align: 'right' });

        currentY += 24;

        expenses.forEach((item, index) => {
          // Page overflow check
          if (currentY > 740) {
            doc.addPage();
            currentY = 40;

            // Re-render table header on new page
            doc.rect(40, currentY, 515, 22).fill(secondaryColor);
            doc
              .fontSize(9)
              .fillColor('#FFFFFF')
              .text('Date', 50, currentY + 6)
              .text('Person', 120, currentY + 6)
              .text('Category', 210, currentY + 6)
              .text('Note / Description', 300, currentY + 6)
              .text('Amount', 460, currentY + 6, { width: 85, align: 'right' });
            currentY += 24;
          }

          // Row alternate background
          if (index % 2 === 1) {
            doc.rect(40, currentY, 515, 20).fill('#F8FAFC');
          }

          doc
            .fontSize(8.5)
            .fillColor(secondaryColor)
            .text(formatDate(item.expense_date), 50, currentY + 4)
            .text(item.member?.display_name || 'Member', 120, currentY + 4, { width: 85, ellipsis: true })
            .text(item.category?.name || 'Category', 210, currentY + 4, { width: 85, ellipsis: true })
            .text(item.note || '-', 300, currentY + 4, { width: 155, ellipsis: true })
            .text(formatCurrency(item.amount), 460, currentY + 4, { width: 85, align: 'right' });

          doc
            .moveTo(40, currentY + 20)
            .lineTo(555, currentY + 20)
            .strokeColor(borderLight)
            .stroke();

          currentY += 21;
        });

        // Total Row at the bottom
        doc.rect(40, currentY + 2, 515, 24).fill('#EEF2FF');
        doc
          .fontSize(10)
          .fillColor(primaryColor)
          .text('Total Expense Amount', 50, currentY + 8)
          .text(formatCurrency(summary.customRangeTotal), 440, currentY + 8, {
            width: 105,
            align: 'right',
          });

        // Footer
        doc
          .fontSize(8)
          .fillColor(textMuted)
          .text('Generated automatically by ExpenseApp • Keep for personal and tax records', 40, 785, {
            align: 'center',
            width: 515,
          });

        doc.end();
      } catch (err) {
        reject(err);
      }
    });
  }
}

